-- =============================================================================
-- 020 - database-level guard on remote_chunks.status (audit H5).
-- =============================================================================
--
-- `backing` means the physical tape write began, so the chunk may already be
-- on the cartridge; `done` means it is. Moving either back to a re-drivable
-- state lets the pipeline fetch and write the chunk a second time. Until this
-- migration that rule lived only in Python (src/pipeline_types.py
-- CHUNK_TRANSITIONS), so a raw UPDATE - or any code path that skipped the
-- validated setter - could break it.
--
-- What the database now refuses, whoever asks:
--
--     backing -> anything except done
--     done    -> anything
--
-- The pre-write states (pending / fetching / packing / fetch_failed /
-- backup_failed) are deliberately NOT policed here: nothing is on tape in any
-- of them, and the application matrix already validates them.
--
-- The one legitimate exception is an operator-driven recovery (today: the
-- destructive tape reset, which erases the cartridge generation a chunk was
-- written to). It must be explicit, named and audited: the caller inserts one
-- row per chunk into remote_chunk_transition_overrides in the SAME transaction,
-- and the guard consumes it. A consumed row is the permanent audit record; an
-- override authorises exactly one transition of exactly one chunk.
--
-- Safe to auto-apply at startup: additive only (one small table, one index,
-- one function, one row trigger), no data rewrite, idempotent.
--
-- Portability note for a non-PostgreSQL backend: the rule itself is plain SQL
-- (the EXISTS predicate below). Only the trigger body is plpgsql. In SQLite
-- the same guard is a `BEFORE UPDATE OF status ... WHEN <condition>` trigger
-- calling RAISE(ABORT, ...), plus an AFTER UPDATE trigger that marks the
-- override consumed.

BEGIN;

-- Serialise concurrent startups: two processes running this file at once
-- would otherwise race on the catalog rows it creates. The key is
-- 0x4C544F38_00000014 ('LTO8', migration 20): transaction-scoped, and distinct
-- from the archiver single-writer lock (0x00000000_4C544F38).
SELECT pg_advisory_xact_lock(5500108146862981140);

CREATE TABLE IF NOT EXISTS remote_chunk_transition_overrides (
    override_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Deliberately no foreign key: the audit record must outlive the chunk
    -- and session rows it describes.
    session_id     BIGINT NOT NULL,
    chunk_index    INTEGER NOT NULL CHECK (chunk_index >= 0),
    from_status    TEXT NOT NULL CHECK (from_status IN ('backing','done')),
    to_status      TEXT NOT NULL CHECK (to_status IN
                       ('pending','fetching','packing','backing','done',
                        'fetch_failed','backup_failed')),
    override_name  TEXT NOT NULL CHECK (length(btrim(override_name)) > 0),
    reason         TEXT NOT NULL CHECK (length(btrim(reason)) > 0),
    authorized_by  TEXT NOT NULL CHECK (length(btrim(authorized_by)) > 0),
    authorized_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    consumed_at    TIMESTAMPTZ,
    CONSTRAINT remote_chunk_transition_overrides_distinct_ck
        CHECK (from_status <> to_status)
);

CREATE INDEX IF NOT EXISTS idx_remote_chunk_transition_overrides_open
    ON remote_chunk_transition_overrides (session_id, chunk_index)
    WHERE consumed_at IS NULL;

CREATE OR REPLACE FUNCTION lto_guard_chunk_status_transition()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    granted BIGINT;
BEGIN
    IF NEW.status IS NOT DISTINCT FROM OLD.status THEN
        RETURN NEW;
    END IF;
    IF NOT (OLD.status = 'done'
            OR (OLD.status = 'backing' AND NEW.status <> 'done')) THEN
        RETURN NEW;
    END IF;

    SELECT o.override_id INTO granted
    FROM remote_chunk_transition_overrides o
    WHERE o.session_id = OLD.session_id
      AND o.chunk_index = OLD.chunk_index
      AND o.from_status = OLD.status
      AND o.to_status = NEW.status
      AND o.consumed_at IS NULL
    ORDER BY o.override_id
    LIMIT 1
    FOR UPDATE;

    IF granted IS NULL THEN
        RAISE EXCEPTION
            'remote chunk %/% may not move % -> %: the chunk may already be on tape. An operator recovery must record a named override in remote_chunk_transition_overrides in the same transaction.',
            OLD.session_id, OLD.chunk_index, OLD.status, NEW.status
            USING ERRCODE = 'check_violation';
    END IF;

    UPDATE remote_chunk_transition_overrides
    SET consumed_at = now()
    WHERE override_id = granted;
    RETURN NEW;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'remote_chunks'::regclass
          AND tgname = 'trg_remote_chunks_status_transition'
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER trg_remote_chunks_status_transition
        BEFORE UPDATE OF status ON remote_chunks
        FOR EACH ROW EXECUTE FUNCTION lto_guard_chunk_status_transition();
    END IF;
END $$;

COMMIT;
